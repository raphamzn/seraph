#!/usr/bin/env python3
"""Regenerate src/qml/components/IconCatalog.qml from src/qml/icons/Icon*.qml.

The catalog is the list of built-in icon names the sidebar's "Customize…"
dialog offers and that SidebarPinnedCard validates against. Run it after
updating the quill-icons submodule and commit the result.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
ICONS = ROOT / "src" / "qml" / "icons"
OUT = ROOT / "src" / "qml" / "components" / "IconCatalog.qml"

names = sorted(
    re.sub(r"^Icon|\.qml$", "", p.name)
    for p in ICONS.glob("Icon*.qml")
)

lines = ",\n".join(f'        "{n}"' for n in names)
OUT.write_text(f'''pragma Singleton
import QtQuick

// Generated by scripts/gen-icon-catalog.py from src/qml/icons — do not edit.
// Names of the built-in icons, without the "Icon" prefix.
QtObject {{
    readonly property var names: [
{lines}
    ]

    function has(name) {{
        return names.indexOf(name) >= 0
    }}

    // Case-insensitive substring filter; an empty query returns everything.
    function matching(query) {{
        var q = (query || "").toLowerCase()
        if (q === "")
            return names
        return names.filter(function(n) {{ return n.toLowerCase().indexOf(q) >= 0 }})
    }}
}}
''')
print(f"{OUT.relative_to(ROOT)}: {len(names)} icons")
